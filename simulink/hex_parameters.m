function P=hex_parameters()
%HEX_PARAMETERS Current six-rotor simulation and control parameters.
% Fault truth remains confined to the plant.
P=hex_base_parameters();
P.duration=24; P.motion_start=1; P.motion_end=7; P.fault_start=3;
P.reference_mode='path_progress';
P.control_tuning_version='control_v3_20261023';
% Fastest tested rise satisfying 35% overshoot / 1.2-s settling limits.
% Attitude gain 8 exceeds the step-overshoot limit. Gain 5 recovers more
% slowly after the motor-1 total-loss transient despite its small overshoot.
P.control.attitude_p(1:2)=7;
r=struct('estimator_tau_s',.025,'estimator_min_command_rad_s',100,...
    'failed_speed_ratio',.06,'healthy_speed_ratio',.98,...
    'position_soft_m',.08,'position_hard_m',.30,...
    'tilt_soft_deg',12,'tilt_hard_deg',25,...
    'rate_soft_rad_s',.6,'rate_hard_rad_s',2,...
    'progress_slow_tau_s',.08,'progress_fast_tau_s',.8,...
    'degraded_position_p',[1.5;1.5;1.4],...
    'degraded_velocity_p',[4;4;3],...
    'degraded_acceleration_limit_m_s2',[1.5;1.5;3],...
    'degraded_tilt_limit_deg',15,'yaw_damping_s_inv',1,...
    'degraded_wrench_priority',[6;3;3;.015]);
P.control.fault_response=r;
P=hex_prepare_inputs(P);
end
