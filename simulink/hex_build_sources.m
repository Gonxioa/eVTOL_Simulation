function manifest=hex_build_sources()
%HEX_BUILD_SOURCES Content identity of every dependency embedded in the SLX.
root=fileparts(mfilename('fullpath'));
paths={'build_hex_model.m','hex_build_sources.m','hex_embedded_scripts.m',...
    'hex_parameters.m','hex_base_parameters.m','hex_common_block_parameters.m',...
    'hex_block_parameters.m','hex_sha256.m','hex_hash_file.m','hex_check_loaded_model.m',...
    'hex_ensure_model.m','hex_finalize_parameters.m','run_hex_simulink.m',...
    'configure_hex_simulink.m','hex_run_identity.m','hex_export_result.m',...
    'hex_signal_names.m','hex_diagnostic_names.m','hex_execution_diagnostics.m',...
    'hex_metrics.m','hex_recovery_metrics.m','hex_prepare_inputs.m','hex_validate_parameters.m',...
    'configs/research.json','internal/layout_template.slx'};
for directory={'blocks','functions'}
    files=dir(fullfile(root,directory{1},'*.m'));
    for i=1:numel(files),paths{end+1}=[directory{1} '/' files(i).name];end %#ok<AGROW>
end
paths=sort(paths);sources=repmat(struct('path','','sha256',''),numel(paths),1);
for i=1:numel(paths)
    sources(i).path=['simulink/' paths{i}];
    sources(i).sha256=hex_hash_file(fullfile(root,paths{i}));
end
manifest=struct('schema','hex_build_v1','sources',sources,...
    'source_signature',hex_sha256(jsonencode(sources)));
end
