function [names,units,frames]=hex_diagnostic_names()
%HEX_DIAGNOSTIC_NAMES Order of the controller's separate diagnostics port.
groups={'velocity_P','velocity_I_applied','velocity_D','acceleration_raw',...
    'acceleration_component_limited','acceleration_force_limited','force_requested_ground',...
    'rate_P','rate_I_applied','rate_D','angular_acceleration_requested','rate_gate_blocked',...
    'rate_error_increment','rate_applied_increment','rate_clip_increment','velocity_error_increment',...
    'velocity_component_backcalc','velocity_vertical_backcalc','velocity_tilt_backcalc',...
    'velocity_total_backcalc','velocity_allocation_backcalc','velocity_clip_increment',...
    'feedback_acceleration_filtered','feedback_angular_acceleration_filtered',...
    'velocity_proportional_gain','velocity_integral_gain','acceleration_component_limit','rate_gate_triggered'};
group_units=[repmat({'m/s^2'},1,6),{'N'},repmat({'rad/s^2'},1,4),{'1'},...
    repmat({'rad/s^2'},1,3),repmat({'m/s^2'},1,8),{'rad/s^2','1/s','1/s^2','m/s^2','1'}];
names=cell(1,3*numel(groups));units=names;frames=names;
for i=1:numel(groups)
    for j=1:3
        k=3*(i-1)+j;names{k}=sprintf('diag_%s_%s',groups{i},char('x'+j-1));
        units{k}=group_units{i};frames{k}='ground';
        if (i>=8 && i<=15) || i==24 || i==28,frames{k}='body';end
    end
end
end
