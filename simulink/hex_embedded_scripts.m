function scripts=hex_embedded_scripts()
%HEX_EMBEDDED_SCRIPTS Single definition used by build and loaded-model checks.
root=fileparts(mfilename('fullpath'));
definitions={...
    'reference_step',{'blocks/reference_step.m','blocks/task_reference.m'},'P_task_reference';...
    'controller_step',{'blocks/controller_step.m','functions/hex_rotation.m','functions/hex_multiply.m',...
        'functions/hex_desired_attitude.m','functions/hex_allocate.m','functions/hex_trf.m','functions/hex_rate_integral.m'},'P_controller_step';...
    'plant_step',{'blocks/plant_step.m','functions/hex_derivative.m','functions/hex_rotation.m','functions/hex_multiply.m'},'P_plant_step';...
    'sensor_step',{'blocks/sensor_step.m','functions/hex_derivative.m','functions/hex_rotation.m','functions/hex_multiply.m'},'P_sensor_step';...
    'fault_schedule',{'blocks/fault_schedule.m'},'P_fault_schedule';...
    'wind_step',{'blocks/wind_step.m'},'P_wind_step';...
    'envelope_step',{'blocks/envelope_step.m'},'P_envelope_step'};
scripts=repmat(struct('function_name','','parameter','','script','','sha256',''),size(definitions,1),1);
for i=1:size(definitions,1)
    pieces=cellfun(@(path)fileread(fullfile(root,path)),definitions{i,2},'UniformOutput',false);
    script=regexprep(strjoin(pieces,newline),'\<P\>',definitions{i,3});
    scripts(i)=struct('function_name',definitions{i,1},'parameter',definitions{i,3},...
        'script',script,'sha256',hex_sha256(script));
end
end
